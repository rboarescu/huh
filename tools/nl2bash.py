"""Turn NL2Bash pairs into held-out eval cases for `huh eval`.

NL2Bash (https://github.com/TellinaTool/nl2bash) is GPL-3.0, so its data is not
committed here. Download it, then generate evals/nl2bash.toml (git-ignored):

    mkdir /tmp/nl2bash && cd /tmp/nl2bash
    curl -LO https://raw.githubusercontent.com/TellinaTool/nl2bash/master/data/bash/all.nl
    curl -LO https://raw.githubusercontent.com/TellinaTool/nl2bash/master/data/bash/all.cm
    python3 -I tools/nl2bash.py /tmp/nl2bash catalog > evals/nl2bash.toml

Only the command pick is scored (no `expect`): NL2Bash answers use flags and
pipelines the catalog does not model. Kept: single commands, no pipes or
redirection, whose program is in the catalog. `find` lines that act on what
they find (-exec, -delete) are dropped, because the right catalog answer for
"delete all .tmp files" is arguably `rm`.
"""
import json, random, re, sys, tomllib
from pathlib import Path

PER_COMMAND = 12
data, catalog = Path(sys.argv[1]), Path(sys.argv[2])
names = {tomllib.loads(p.read_text())["name"] for p in catalog.glob("*.toml")}
requests = (data / "all.nl").read_text(errors="replace").splitlines()
commands = (data / "all.cm").read_text(errors="replace").splitlines()

by_command = {}
for request, line in zip(requests, commands):
    if re.search(r"[|;&<>`]|\$\(", line) or len(request) > 160 or '"""' in request:
        continue
    words = line.split()
    if words and words[0] == "sudo":
        words = words[1:]
    if not words:
        continue
    name = " ".join(words[:2]) if " ".join(words[:2]) in names else words[0]
    if name not in names:
        continue
    if name == "find" and re.search(r"-exec|-delete|-ok\b|-print0", line):
        continue
    by_command.setdefault(name, []).append((request.strip(), line.strip()))

rng = random.Random(2026)
print("# Generated by tools/nl2bash.py from NL2Bash (GPL-3.0). Do not commit. Never tune on this.")
for name in sorted(by_command):
    pairs = sorted(set(by_command[name]))
    rng.shuffle(pairs)
    for request, line in pairs[:PER_COMMAND]:
        print(f"\n# {line}\n[[case]]\nrequest = {json.dumps(request)}\ncommand = {json.dumps(name)}")
